"""ETL Step 4: enzyme-reaction edge table -- A class (has source_type, replaced by
source).

## Three old defects

1. **edge_id generated by position.** The original `EDGE{i+1:07d}` numbered rows by
   order after de-duplication, but the dedupe key is `(enzyme_id, reaction_id)` --
   inserting a new row in the middle shifts every later number, so a new pair got an
   already-taken ID -> PK conflict. Changed to the same "number persistence" as
   enzyme_id: existing pairs keep their original number, new pairs take `MAX+1`.
   Re-runs are idempotent and numbers are never reused.

2. **"Read existing -> filter out the ones already there" = skip if it exists.** Field
   changes on existing edges never take effect (violates "supplement only + insert
   only"). Changed to upsert.

3. **`range(1, 46)` hard-coded the column width** -- fixed: derived from the `Enzyme_N`
   columns actually present in `df.columns`. Measured on the committed pairs table,
   `max_n` is exactly 45 (zero slack); one more enzyme would be silently dropped.

## source_type comes from the enzyme table, not guessed from the file name

An edge's source = its enzyme's source. `enzyme.source_type` is already written and
authoritative in step 2, and both paths (the rhea child table / the pairs table) can
read it uniformly -- pairs is a merged table, which has no per-enzyme source column to
begin with.
"""
import os
import sys

import pandas as pd
from sqlalchemy import create_engine

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from cell_values import split_multi_value  # noqa: E402
from config import DB_URL  # noqa: E402
from db_utils import upsert_dataframe  # noqa: E402
from sources import read_merged, read_segmented  # noqa: E402

engine = create_engine(DB_URL)

RHEA_FILE = 'for_enzyme_detail/child_tables/uniprotkb_rhea.tsv'
PAIRS_FILE = 'for_graph/uniprotkb_terpene_pairs.tsv'


def _get_id_map(table, external_col, internal_col):
    """Map external ID -> internal ID."""
    df = pd.read_sql(f"SELECT {external_col}, {internal_col} FROM {table}", engine)
    return dict(zip(df[external_col], df[internal_col]))


def _enzyme_attrs():
    """enzyme_id -> (source_type, review_status). An edge's source attributes are
    copied verbatim from its enzyme."""
    df = pd.read_sql("SELECT enzyme_id, source_type, review_status FROM enzyme", engine)
    return {str(r.enzyme_id): (str(r.source_type), str(r.review_status))
            for r in df.itertuples()}


def load_edges_from_rhea(only=None):
    """uniprotkb_rhea.tsv: one row = one enzyme-reaction edge."""
    df = read_segmented(RHEA_FILE, only=only, dtype=str)

    edges = df[["Entry", "Rhea ID"]].dropna(subset=["Rhea ID", "Entry"]).copy()
    edges = edges[(edges["Rhea ID"].astype(str).str.strip() != "")
                  & (edges["Entry"].astype(str).str.strip() != "")]
    edges = edges.drop_duplicates()

    enzyme_map = _get_id_map("enzyme", "uniprot_id", "enzyme_id")
    reaction_map = _get_id_map("reaction", "rhea_id", "reaction_id")

    edges["enzyme_id"] = edges["Entry"].map(enzyme_map)
    edges["reaction_id"] = edges["Rhea ID"].map(reaction_map)
    edges = edges.dropna(subset=["enzyme_id", "reaction_id"])

    return pd.DataFrame({"enzyme_id": edges["enzyme_id"], "reaction_id": edges["reaction_id"]})


def load_edges_from_pairs(only=None):
    """Expand the wide table terpene_pairs.tsv: one substrate-product pair -> N enzymes.

    pairs is a **merged table** (no suffix): under the same compound pair, enzymes from
    both sources sit on the same row, so it cannot be source-segmented. With only=<s>
    it filters by enzyme source, so the other source's edges are not recomputed too.
    """
    df = read_merged(PAIRS_FILE, dtype=str)

    enzyme_map = _get_id_map("enzyme", "uniprot_id", "enzyme_id")
    reaction_map = _get_id_map("reaction", "rhea_id", "reaction_id")
    attrs = _enzyme_attrs()

    # Column width is derived from the Enzyme_N columns actually present, not a
    # hard-coded cap -- build_terpene_pairs.py's max_n follows the data. Hard-coding
    # silently drops rows once enzymes grow: the committed pairs table has max_n
    # exactly 45, zero slack.
    max_n = max(
        (int(c[len('Enzyme_'):]) for c in df.columns
         if c.startswith('Enzyme_') and c[len('Enzyme_'):].isdigit()),
        default=0,
    )

    rows = []
    for _, row in df.iterrows():
        for i in range(1, max_n + 1):
            enzyme_col = f"Enzyme_{i}"
            rhea_col = f"Rhea ID_{i}"
            if enzyme_col not in df.columns or rhea_col not in df.columns:
                continue
            entry = str(row.get(enzyme_col) or '').strip()
            if not entry:
                continue
            enz_id = enzyme_map.get(entry)
            if not enz_id:
                continue
            if only and attrs.get(enz_id, ('', ''))[0] != only:
                continue
            # Rhea ID_i may be a '; '-joined multi-value cell (see cell_values.py):
            # split it and build one edge per value. Looking up the whole string in
            # reaction_map always missed, silently dropping those edges.
            for one_rhea in split_multi_value(row.get(rhea_col)):
                rxn_id = reaction_map.get(one_rhea)
                if rxn_id:
                    rows.append({"enzyme_id": enz_id, "reaction_id": rxn_id})

    if not rows:
        return pd.DataFrame(columns=["enzyme_id", "reaction_id"])
    return pd.DataFrame(rows).drop_duplicates()


# purge **deletes this source's edges first** (without that, enzyme cannot be deleted,
# the FK blocks it), so the numbers vanish with them. So etl_run calls
# snapshot_edge_ids() before purge to save a copy, letting re-inserted edges keep their
# original numbers -- otherwise every single-source refresh renumbers all of that
# source's edges.
_SEED_EDGE_IDS = {}


def snapshot_edge_ids():
    """Take a (enzyme_id, reaction_id) -> edge_id snapshot before purge. Called by
    etl_run."""
    global _SEED_EDGE_IDS
    with engine.connect() as conn:
        ex = pd.read_sql("SELECT edge_id, enzyme_id, reaction_id FROM enzyme_reaction_edge", conn)
    _SEED_EDGE_IDS = {(str(a), str(b)): str(e)
                      for e, a, b in zip(ex.edge_id, ex.enzyme_id, ex.reaction_id)}
    print(f'  edge_id 快照: {len(_SEED_EDGE_IDS)} 条 (purge 前)')
    return _SEED_EDGE_IDS


def _assign_edge_ids(all_edges):
    """Existing pairs keep their original number, new pairs take MAX+1. Re-runs are
    idempotent, numbers are not reused.

    Number sources = the pre-purge snapshot ∪ the current table. The snapshot covers
    the source that was cleared, the current table covers the other source, and the
    union is the complete pre-refresh numbering.
    """
    with engine.connect() as conn:
        ex = pd.read_sql("SELECT edge_id, enzyme_id, reaction_id FROM enzyme_reaction_edge", conn)
    known = dict(_SEED_EDGE_IDS)
    known.update({(str(a), str(b)): str(e)
                  for e, a, b in zip(ex.edge_id, ex.enzyme_id, ex.reaction_id)})
    nxt = 1 + max((int(e[4:]) for e in known.values()
                   if e.startswith('EDGE') and e[4:].isdigit()), default=0)

    ids, reused, allocated = [], 0, 0
    for enz, rxn in zip(all_edges["enzyme_id"], all_edges["reaction_id"]):
        eid = known.get((str(enz), str(rxn)))
        if eid:
            reused += 1
        else:
            eid = f'EDGE{nxt:07d}'
            nxt += 1
            allocated += 1
        ids.append(eid)
    all_edges['edge_id'] = ids
    print(f'  edge_id: 沿用 {reused}, 新分配 {allocated}')
    return all_edges


def load_edges(only=None):
    attrs = _enzyme_attrs()

    parts = [load_edges_from_rhea(only=only), load_edges_from_pairs(only=only)]
    all_edges = pd.concat([p for p in parts if not p.empty], ignore_index=True)
    if all_edges.empty:
        print('  enzyme_reaction_edge: 没有边')
        return
    all_edges = all_edges.drop_duplicates(subset=["enzyme_id", "reaction_id"]).reset_index(drop=True)

    missing = [e for e in all_edges['enzyme_id'] if e not in attrs]
    if missing:
        raise KeyError(f'{len(missing)} 条边的 enzyme_id 不在 enzyme 表里, 例如 {missing[:3]}; '
                       'source_type 无处可取')

    all_edges['source_type'] = [attrs[e][0] for e in all_edges['enzyme_id']]
    all_edges['review_status'] = [attrs[e][1] for e in all_edges['enzyme_id']]
    all_edges = _assign_edge_ids(all_edges)

    cols = ["edge_id", "enzyme_id", "reaction_id", "source_type", "review_status"]
    with engine.begin() as conn:
        n = upsert_dataframe(conn, "enzyme_reaction_edge", all_edges[cols],
                             update_cols=["source_type", "review_status"])
    print(f'  enzyme_reaction_edge: upsert {n} 行 (幂等; 已有边沿用原编号)')
    for s in sorted(set(all_edges['source_type'])):
        print(f'     {s}: {int((all_edges.source_type == s).sum())}')


if __name__ == "__main__":
    load_edges()


def run(only=None):
    load_edges(only=only)
